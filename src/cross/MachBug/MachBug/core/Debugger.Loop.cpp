    {
        return mThreads.Known().size();
    }

    void Debugger::refreshModules()
    {
        if(!mProcess)
            return;

        const Modules::Change change = mModules.Refresh(mProcess->task);
        for(const Modules::Image& image : change.appeared)
            cbLoadModule(image.loadAddress, image.path);
        for(const Modules::Image& image : change.disappeared)
            cbUnloadModule(image.loadAddress);
    }

    std::vector<Modules::Image> Debugger::LoadedModules() const
    {
        return mModules.Known();
    }

    std::size_t Debugger::ModuleCount() const
    {
        return mModules.Known().size();
    }

    void Debugger::refreshThreads()
    {
        if(!mProcess)
            return;

        const Threads::Change change = mThreads.Refresh(mProcess->task);
        for(const uint64_t threadId : change.appeared)
        {
            // Before the callback, not after: a caller told about a new thread may go straight
            // to reading its state, and the breakpoints this engine promised are part of that
            // state. A thread born after a hardware breakpoint was set carries none of it until
            // this write happens.
            std::string applyError;
            if(!mBreakpoints.ApplyToThread(kLoopArch, mThreads.PortFor(threadId), &applyError))
                cbInternalError("could not arm the hardware breakpoints on a new thread: " +
                                 applyError);
            cbThreadCreate(threadId);
        }
        for(const uint64_t threadId : change.disappeared)
            cbThreadExit(threadId);
    }

    mach_port_t Debugger::StoppedThread() const
    {
        return mStoppedThread.load(std::memory_order_acquire);
    }

    mach_port_t Debugger::ResolveThread(const uint64_t threadId) const
    {
        if(threadId == 0)
            return StoppedThread();

        // A system thread id, not a port name. Milestone 4 measured why that distinction has to
        // exist: task_threads mints fresh send rights on every call, so a port name identifies a
        // thread only until the next poll -- naming threads that way reported a three-thread
        // target as three creations and handed back ids that no longer resolved. Threads holds
        // one right per live thread and maps the stable id onto it.
        return mThreads.PortFor(threadId);
    }

