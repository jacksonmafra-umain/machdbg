// The exception loop: Start(), the four thread-safe commands, and the receive loop that turns
// Mach exception messages into cb*() callbacks. This is the file with no ElfBug counterpart --
// see the class comment at the top of Debugger.h for why ElfBug's waitpid()-shaped debugLoop()
// does not transfer here, and ExceptionServer.cpp for the MIG entry point that calls into
// handleException() below.
//
// mach_msg send/receive error codes are reported through mach_error_string() directly rather
// than Process::DescribeKernReturn(): that helper's KERN_FAILURE branch is deliberately worded
// for task_for_pid's most common failure (a missing get-task-allow entitlement) and would be
// misleading attached to a send/receive error that has nothing to do with entitlements.

#include <MachBug/core/Debugger.h>

#include <mach/mach_error.h>
#include <mach/thread_status.h>
#include <sys/wait.h>
#include <csignal>
#include <cerrno>
#include <cstring>

// ARM_THREAD_STATE64 / x86_THREAD_STATE64 (see kExceptionPortStateFlavor, below) already reach
// this file transitively through <mach/thread_status.h> -> <mach/machine/thread_status.h> ->
// <mach/arm/thread_status.h> or <mach/i386/thread_status.h>, picked by the same architecture
// macros used here. These direct includes are redundant but make that dependency explicit rather
// than implicit in a transitive header chain.
#if defined(__x86_64__)
#include <mach/i386/thread_status.h>
#elif defined(__arm64__) || defined(__aarch64__)
#include <mach/arm/thread_status.h>
#endif

// Generated by MIG from mach_exc.defs (see MachBug/cmake/MachBugMig.cmake). Declares
// mach_exc_server, the dispatch routine that turns a raw exception message into a call to
// catch_mach_exception_raise_state_identity() (ExceptionServer.cpp) or one of its two
// never-used siblings (MachBugMigStubs.c).
extern "C" {
#include "mach_exc.h"
}

